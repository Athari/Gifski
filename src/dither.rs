#[inline(always)]
fn color_diff_rgb(c1: RGBA8, c2: RGBA8) -> u32 {
    let dr = c1.r as i32 - c2.r as i32;
    let dg = c1.g as i32 - c2.g as i32;
    let db = c1.b as i32 - c2.b as i32;
    let l1 = c1.r as i32 * 299 + c1.g as i32 * 587 + c1.b as i32 * 114;
    let l2 = c2.r as i32 * 299 + c2.g as i32 * 587 + c2.b as i32 * 114;
    let dl = (l1 - l2) / 1000;
    ((dr * dr * 299 + dg * dg * 587 + db * db * 114) * 3 / 4000 + dl * dl) as u32
}

#[derive(Copy, Clone)]
struct PaletteColor {
    idx: u8,
    color: RGBA8,
    r: f32,
    g: f32,
    b: f32,
    luma: f32,
}

impl PaletteColor {
    #[inline(always)]
    fn new(idx: u8, color: RGBA8) -> Self {
        let r = color.r as f32;
        let g = color.g as f32;
        let b = color.b as f32;
        let luma = (r * 299.0 + g * 587.0 + b * 114.0) * 0.001;
        Self { idx, color, r, g, b, luma }
    }
}

#[derive(Copy, Clone)]
struct KdNode {
    pal: PaletteColor,
    axis: u8,
    left: u16,
    right: u16,
}

struct KdTree {
    nodes: Vec<KdNode>,
    root: u16,
}

impl KdTree {
    fn build(mut colors: Vec<PaletteColor>) -> Self {
        let mut nodes = Vec::with_capacity(colors.len());
        let root = Self::build_subtree(&mut colors, 0, &mut nodes);
        Self { nodes, root }
    }

    fn build_subtree(colors: &mut [PaletteColor], depth: usize, nodes: &mut Vec<KdNode>) -> u16 {
        if colors.is_empty() {
            return u16::MAX;
        }

        let axis = (depth % 3) as u8;
        match axis {
            0 => colors.sort_unstable_by(|a, b| a.r.total_cmp(&b.r)),
            1 => colors.sort_unstable_by(|a, b| a.g.total_cmp(&b.g)),
            _ => colors.sort_unstable_by(|a, b| a.b.total_cmp(&b.b)),
        }

        let mid = colors.len() / 2;
        let pal = colors[mid];
        let node_idx = nodes.len() as u16;

        nodes.push(KdNode { pal, axis, left: u16::MAX, right: u16::MAX });

        let left = Self::build_subtree(&mut colors[..mid], depth + 1, nodes);
        let right = Self::build_subtree(&mut colors[mid + 1..], depth + 1, nodes);

        nodes[node_idx as usize].left = left;
        nodes[node_idx as usize].right = right;

        node_idx
    }

    #[inline(always)]
    fn find_nearest(&self, r: f32, g: f32, b: f32) -> (u8, RGBA8) {
        if self.nodes.is_empty() {
            return (0, RGBA8::new(0, 0, 0, 255));
        }

        let query_luma = (r * 299.0 + g * 587.0 + b * 114.0) * 0.001;
        let mut best_diff = f32::MAX;
        let mut best_idx = self.nodes[0].pal.idx;
        let mut best_color = self.nodes[0].pal.color;

        let mut stack = [0u16; 32];
        let mut stack_top = 0;
        stack[0] = self.root;
        stack_top += 1;

        while stack_top > 0 {
            stack_top -= 1;
            let curr = stack[stack_top];
            if curr == u16::MAX {
                continue;
            }
            let node = &self.nodes[curr as usize];

            let dr = r - node.pal.r;
            let dg = g - node.pal.g;
            let db = b - node.pal.b;
            let dl = query_luma - node.pal.luma;
            let diff = (dr * dr * 0.299 + dg * dg * 0.587 + db * db * 0.114) * 0.75 + dl * dl;

            if diff < best_diff {
                best_diff = diff;
                best_idx = node.pal.idx;
                best_color = node.pal.color;
            }

            let (delta, axis_weight) = match node.axis {
                0 => (dr, 0.22425f32),
                1 => (dg, 0.44025f32),
                _ => (db, 0.0855f32),
            };

            let (closer, farther) = if delta <= 0.0 {
                (node.left, node.right)
            } else {
                (node.right, node.left)
            };

            if farther != u16::MAX && (delta * delta * axis_weight) < best_diff {
                stack[stack_top] = farther;
                stack_top += 1;
            }
            if closer != u16::MAX {
                stack[stack_top] = closer;
                stack_top += 1;
            }
        }

        (best_idx, best_color)
    }
}

/// Minimum number of dissimilar neighbors in the 3x3 window required to trigger edge-aware dithering suppression.
/// A straight orthogonal edge across the center pixel has exactly 3 neighbors across the boundary line.
const EDGE_DISSIMILAR_MIN: usize = 3;

const CANDIDATE_CACHE_SIZE: usize = 65536;

#[derive(Copy, Clone, SmartDefault)]
struct CandidateCacheEntry {
    #[default(u32::MAX)]
    key: u32,
    nearest: u8,
    candidates: [u8; 16],
}

/// Context storing precomputed palette structures and candidate cache across frames.
pub struct DitherColorContext {
    kd_tree: Option<KdTree>,
    palette_luma: [u32; 256],
    candidate_cache: Vec<CandidateCacheEntry>,
    palette: Vec<RGBA8>,
    k: usize,
    dithering_level: f32,
}

impl Default for DitherColorContext {
    fn default() -> Self {
        Self::new()
    }
}

impl DitherColorContext {
    #[must_use]
    pub fn new() -> Self {
        Self {
            kd_tree: None,
            palette_luma: [0; 256],
            candidate_cache: vec![CandidateCacheEntry::default(); CANDIDATE_CACHE_SIZE],
            palette: Vec::new(),
            k: 0,
            dithering_level: -1.0,
        }
    }
}

/// Dither colors using Thomas Knoll's pattern dithering (local error feedback).
#[allow(clippy::too_many_arguments)]
#[inline(never)]
pub fn dither_color(
    image: ImgRef<RGBA8>,
    palette: &[RGBA8],
    matrix: DitherMatrix,
    dithering_level: f32,
    exact_match: bool,
    background: Option<ImgRef<RGBA8>>,
    out: &mut [u8],
    context: &mut DitherColorContext,
    edge_threshold: u8,
) {
    let width = image.width();
    let height = image.height();

    let transparent_index = palette.iter().position(|p| p.a <= 128).map(|i| i as u8);

    // Number of candidate colors per pixel. Thomas Knoll's pattern dithering algorithm
    // was originally designed for a 4x4 Bayer matrix using 16 candidates. For larger matrices
    // (e.g. 8x8 or 32x32 blue noise), candidate generation is capped at 16 to avoid performance degradation.
    let k = (matrix.width * matrix.height).min(16);

    if context.palette != palette || context.k != k || context.dithering_level != dithering_level {
        context.palette = palette.to_vec();
        context.k = k;
        context.dithering_level = dithering_level;

        let mut opaque_palette = Vec::with_capacity(palette.len());
        for (i, &p) in palette.iter().enumerate() {
            if p.a > 128 {
                opaque_palette.push((i as u8, p));
            }
        }
        if opaque_palette.is_empty() {
            for (i, &p) in palette.iter().enumerate() {
                opaque_palette.push((i as u8, p));
            }
        }

        let fast_palette: Vec<PaletteColor> = opaque_palette.iter().map(|&(idx, color)| PaletteColor::new(idx, color)).collect();
        context.kd_tree = Some(KdTree::build(fast_palette));
        for (i, p) in palette.iter().enumerate() {
            context.palette_luma[i] = p.r as u32 * 299 + p.g as u32 * 587 + p.b as u32 * 114;
        }
        context.candidate_cache.fill(CandidateCacheEntry::default());
    }

    let kd_tree = context.kd_tree.as_ref().unwrap();
    let palette_luma = &context.palette_luma;
    let candidate_cache = &mut context.candidate_cache;

    let x_mask = matrix.width - 1;
    let y_mask = matrix.height - 1;
    let m_width = matrix.width;
    let max_val = matrix.max_val as usize;
    let edge_threshold_sq = (u32::from(edge_threshold) * u32::from(edge_threshold)) * 6;

    for y in 0..height {
        let stride = image.stride();
        let img_row = &image.buf()[y * stride..y * stride + width];
        let out_row = &mut out[y * width..(y + 1) * width];
        let bg_row = background.map(|bg| &bg.buf()[y * bg.stride()..y * bg.stride() + width]);

        let has_top = y > 0;
        let has_bot = y + 1 < height;
        let top_row = if has_top { Some(&image.buf()[(y - 1) * stride..(y - 1) * stride + width]) } else { None };
        let bot_row = if has_bot { Some(&image.buf()[(y + 1) * stride..(y + 1) * stride + width]) } else { None };

        let mut prev_px: Option<RGBA8> = None;
        let mut candidates = [0u8; 64];
        let mut nearest_idx = 0u8;

        for x in 0..width {
            let px = img_row[x];
            if px.a <= 128 {
                if let Some(trans) = transparent_index {
                    out_row[x] = trans;
                    continue;
                }
            }

            if prev_px != Some(px) {
                prev_px = Some(px);

                let key = (px.r as u32) | ((px.g as u32) << 8) | ((px.b as u32) << 16);
                let cache_idx = ((key.wrapping_mul(0x9E3779B9)) >> 16) as usize & (CANDIDATE_CACHE_SIZE - 1);

                if candidate_cache[cache_idx].key == key {
                    nearest_idx = candidate_cache[cache_idx].nearest;
                    candidates[..k].copy_from_slice(&candidate_cache[cache_idx].candidates[..k]);
                } else {
                    let px_r = px.r as f32;
                    let px_g = px.g as f32;
                    let px_b = px.b as f32;

                    if dithering_level == 0.0 {
                        let (nearest, _) = kd_tree.find_nearest(px_r, px_g, px_b);
                        nearest_idx = nearest;
                        candidates[..k].fill(nearest_idx);
                    } else {
                        let mut err_r = 0.0f32;
                        let mut err_g = 0.0f32;
                        let mut err_b = 0.0f32;
                        for (step, cand) in candidates[..k].iter_mut().enumerate() {
                            let tr = (px_r + err_r).clamp(0.0, 255.0);
                            let tg = (px_g + err_g).clamp(0.0, 255.0);
                            let tb = (px_b + err_b).clamp(0.0, 255.0);
                            let (chosen_idx, chosen_color) = kd_tree.find_nearest(tr, tg, tb);
                            if step == 0 {
                                nearest_idx = chosen_idx;
                            }
                            *cand = chosen_idx;
                            err_r = (err_r + (px_r - chosen_color.r as f32)) * dithering_level;
                            err_g = (err_g + (px_g - chosen_color.g as f32)) * dithering_level;
                            err_b = (err_b + (px_b - chosen_color.b as f32)) * dithering_level;
                        }
                        candidates[..k].sort_unstable_by_key(|&idx| palette_luma[idx as usize]);
                    }

                    candidate_cache[cache_idx].key = key;
                    candidate_cache[cache_idx].nearest = nearest_idx;
                    candidate_cache[cache_idx].candidates[..k].copy_from_slice(&candidates[..k]);
                }
            }

            let is_edge = if edge_threshold > 0 {
                let mut dissimilar_count = 0;

                if let (Some(top), Some(bot)) = (top_row, bot_row) {
                    if x > 0 && x + 1 < width {
                        let neighbors = [
                            top[x - 1],
                            top[x],
                            top[x + 1],
                            img_row[x - 1],
                            img_row[x + 1],
                            bot[x - 1],
                            bot[x],
                            bot[x + 1],
                        ];
                        for n_px in neighbors {
                            if n_px.a <= 128 || color_diff_rgb(px, n_px) > edge_threshold_sq {
                                dissimilar_count += 1;
                                if dissimilar_count >= EDGE_DISSIMILAR_MIN {
                                    break;
                                }
                            }
                        }
                    } else {
                        let x_prev = x.saturating_sub(1);
                        let x_next = (x + 1).min(width - 1);
                        let neighbors = [
                            top[x_prev],
                            top[x],
                            top[x_next],
                            img_row[x_prev],
                            img_row[x_next],
                            bot[x_prev],
                            bot[x],
                            bot[x_next],
                        ];
                        for n_px in neighbors {
                            if n_px.a <= 128 || color_diff_rgb(px, n_px) > edge_threshold_sq {
                                dissimilar_count += 1;
                                if dissimilar_count >= EDGE_DISSIMILAR_MIN {
                                    break;
                                }
                            }
                        }
                    }
                } else {
                    let y_prev = y.saturating_sub(1);
                    let y_next = (y + 1).min(height - 1);
                    let x_prev = x.saturating_sub(1);
                    let x_next = (x + 1).min(width - 1);

                    let neighbors = [
                        (x_prev, y_prev),
                        (x,      y_prev),
                        (x_next, y_prev),
                        (x_prev, y),
                        (x_next, y),
                        (x_prev, y_next),
                        (x,      y_next),
                        (x_next, y_next),
                    ];
                    for (nx, ny) in neighbors {
                        let n_px = image.buf()[ny * stride + nx];
                        if n_px.a <= 128 || color_diff_rgb(px, n_px) > edge_threshold_sq {
                            dissimilar_count += 1;
                            if dissimilar_count >= EDGE_DISSIMILAR_MIN {
                                break;
                            }
                        }
                    }
                }

                dissimilar_count >= EDGE_DISSIMILAR_MIN
            } else {
                false
            };

            let dithered_idx = if is_edge {
                nearest_idx
            } else {
                let dither_val = matrix.data[(y & y_mask) * m_width + (x & x_mask)] as usize;
                candidates[(dither_val * k) / (max_val + 1)]
            };

            let mut final_idx = dithered_idx;
            if let (Some(bg_row), Some(trans_idx)) = (bg_row, transparent_index) {
                let bg_px = bg_row[x];
                if bg_px.a > 128 {
                    let dithered_color = palette[dithered_idx as usize];
                    let matches_bg = if exact_match {
                        dithered_color.rgb() == bg_px.rgb()
                    } else {
                        let dither_diff = color_diff_rgb(px, dithered_color);
                        let bg_diff = color_diff_rgb(px, bg_px);
                        bg_diff <= dither_diff
                    };
                    if matches_bg {
                        final_idx = trans_idx;
                    }
                }
            }

            out_row[x] = final_idx;
        }
    }
}

/// Matches dithered palette indices against the background canvas and replaces matching pixels with `transparent_index`.
pub fn apply_background_transparency(
    out_row: &mut [u8],
    source_row: &[RGBA8],
    bg_row: &[RGBA8],
    palette: &[RGBA8],
    transparent_index: u8,
    exact_match: bool,
) {
    for (x, out_px) in out_row.iter_mut().enumerate() {
        let px = source_row[x];
        if px.a <= 128 {
            *out_px = transparent_index;
            continue;
        }
        let bg_px = bg_row[x];
        if bg_px.a > 128 {
            let dithered_color = palette[*out_px as usize];
            let matches_bg = if exact_match {
                dithered_color.rgb() == bg_px.rgb()
            } else {
                let dither_diff = color_diff_rgb(px, dithered_color);
                let bg_diff = color_diff_rgb(px, bg_px);
                bg_diff <= dither_diff
            };
            if matches_bg {
                *out_px = transparent_index;
            }
        }
    }
}

/// Minimum number of 3x3 neighbors that must be within the color similarity threshold.
pub const SPATIAL_SIMILAR_MIN: usize = 5;

/// Minimum number of 3x3 neighbors that must have the exact same palette index.
pub const SPATIAL_EXACT_MIN: usize = 3;

/// Denoises single stray oscillating pixels in a dithered palette-indexed frame.
///
/// Looks at the 3x3 spatial neighborhood in `current_frame` to find a dominant palette color
/// (at least `SPATIAL_EXACT_MIN` exact matches and `SPATIAL_SIMILAR_MIN` similar neighbors).
/// If the center pixel deviates from this dominant color by no more than `threshold`, and the temporal
/// neighbors strictly equal the dominant color across `prev_frames` and `next_frames`, it is replaced
/// with the dominant color.
///
/// Temporal continuity rule: if a neighbor at distance r=1 is outside the threshold,
/// any neighbor at r=2 on the same side is also treated as outside the threshold.
#[allow(clippy::too_many_arguments)]
pub fn denoise_dithered_frame(
    current_frame: &mut [u8],
    width: usize,
    height: usize,
    prev_frames: &[&[u8]], // ordered by distance from center: [dist1, dist2]
    next_frames: &[&[u8]], // ordered by distance from center: [dist1, dist2]
    palette: &[RGBA8],
    radius: u8,
    threshold: u8,
    transparent_index: Option<u8>,
) {
    if radius == 0 || threshold == 0 || width < 3 || height < 3 {
        return;
    }

    let threshold_sq = (u32::from(threshold) * u32::from(threshold)) * 6;
    let src = current_frame.to_vec();

    for y in 1..height - 1 {
        let top_y = (y - 1) * width;
        let mid_y = y * width;
        let bot_y = (y + 1) * width;

        for x in 1..width - 1 {
            let idx = mid_y + x;
            let center_idx = src[idx];
            if Some(center_idx) == transparent_index {
                continue;
            }

            let neighbors = [
                src[top_y + (x - 1)],
                src[top_y + x],
                src[top_y + (x + 1)],
                src[mid_y + (x - 1)],
                src[mid_y + (x + 1)],
                src[bot_y + (x - 1)],
                src[bot_y + x],
                src[bot_y + (x + 1)],
            ];

            let mut majority_idx = None;
            for i in 0..5 {
                let candidate = neighbors[i];
                if Some(candidate) == transparent_index {
                    continue;
                }
                if i > 0 && neighbors[0..i].contains(&candidate) {
                    continue;
                }
                let exact_count = neighbors.iter().filter(|&&c| c == candidate).count();
                if exact_count >= SPATIAL_EXACT_MIN {
                    let c_cand = palette[candidate as usize];
                    let similar_count = neighbors.iter().filter(|&&c| {
                        Some(c) != transparent_index && color_diff_rgb(palette[c as usize], c_cand) <= threshold_sq
                    }).count();
                    if similar_count >= SPATIAL_SIMILAR_MIN {
                        majority_idx = Some(candidate);
                        break;
                    }
                }
            }

            let Some(maj_idx) = majority_idx else {
                continue;
            };

            // Tested pixel must not be equal to majority
            if center_idx == maj_idx {
                continue;
            }

            let c_maj = palette[maj_idx as usize];
            let p_center = palette[center_idx as usize];

            // Content preservation check: if color difference is too large, it is genuine content.
            if color_diff_rgb(p_center, c_maj) > threshold_sq {
                continue;
            }

            // Temporal column check: temporal neighbors must strictly equal maj_idx
            let match_prev1 = !prev_frames.is_empty() && prev_frames[0][idx] == maj_idx;
            let match_prev2 = match_prev1 && (prev_frames.len() > 1 && prev_frames[1][idx] == maj_idx);

            let match_next1 = !next_frames.is_empty() && next_frames[0][idx] == maj_idx;
            let match_next2 = match_next1 && (next_frames.len() > 1 && next_frames[1][idx] == maj_idx);

            let should_replace = if radius == 1 {
                match_prev1 && match_next1
            } else if radius == 2 {
                let matches = (match_prev1 as u8) + (match_prev2 as u8) + (match_next1 as u8) + (match_next2 as u8);
                matches >= 3
            } else {
                false
            };

            if should_replace {
                current_frame[idx] = maj_idx;
            }
        }
    }
}

